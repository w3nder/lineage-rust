use crate::window::WindowId;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum WindowParent {
    PrimaryRoot,
    SecondaryRoot,
    ConsoleManager,
    Window(WindowId),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RootRegistration {
    pub vtable: u32,
    pub flags_argument: u32,
}

pub fn original_root_registration(parent: WindowParent) -> Option<RootRegistration> {
    let vtable = match parent {
        WindowParent::PrimaryRoot => 0x101afdc0,
        WindowParent::SecondaryRoot => 0x101b6db0,
        WindowParent::ConsoleManager | WindowParent::Window(_) => return None,
    };
    Some(RootRegistration { vtable, flags_argument: 0xa })
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct WindowOwner {
    pub parent: WindowParent,
    pub slot: u32,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct WindowRegistration {
    pub call_address: u32,
    pub flags_argument: u32,
    pub vtable: u32,
}

