pub fn hovered_quad(regions: &[(crate::window::WindowId, crate::draw::ButtonRegion)], under: crate::window::WindowId, x: i32, y: i32) -> Option<usize> {
    regions.iter().rev().find(|(id, button)| *id == under && button.contains(x, y)).map(|(_, button)| button.quad)
}

pub fn over_face(texture: &str) -> Option<String> {
    OVER_FACES.iter().any(|normal| normal.eq_ignore_ascii_case(texture)).then(|| format!("{texture}_over"))
}

#[cfg(test)]
mod tests {
    #[test]
    fn mouse_move_0x10034390_reaches_a_disabled_button_and_ncbutton_100012e0_shows_the_over_face_without_testing_enabled() {
        use crate::draw::ButtonRegion;
        use crate::window::WindowId;
        let region = |enabled: bool, quad: usize| ButtonRegion { x: 10, y: 10, w: 20, h: 20, enabled, quad, close: false, silent: false };
        let regions = [(WindowId::MENU, region(true, 3)), (WindowId::MENU, region(false, 7))];
        assert_eq!(hovered_quad(&regions, WindowId::MENU, 15, 15), Some(7));
        assert_eq!(hovered_quad(&regions[..1], WindowId::MENU, 15, 15), Some(3));
        assert_eq!(hovered_quad(&regions, WindowId::MENU, 40, 15), None);
        assert_eq!(hovered_quad(&regions, WindowId::STATUS, 15, 15), None);
    }

    use super::*;
}
